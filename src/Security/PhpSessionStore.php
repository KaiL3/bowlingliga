<?php

declare(strict_types=1);

namespace Bowlingliga\Security;

/**
 * PHP session store based on `$_SESSION` (implementation of the
 * {@see SessionStore} port).
 *
 * Starts a PHP session with secure cookie attributes if needed (`HttpOnly`,
 * `SameSite=Strict` and – if the request runs over HTTPS – `Secure`), so that
 * the session cookie cannot be read via JavaScript and is not sent along with
 * insecure/cross-site requests. After a successful login the session id is
 * regenerated (protection against session fixation, R5.2).
 *
 * This class encapsulates all access to the global session state, so that the
 * {@see AuthModule} flow itself stays free of PHP session details and thus
 * testable.
 */
final class PhpSessionStore implements SessionStore
{
    /**
     * Ensures that a PHP session with secure cookie attributes is active. If a
     * session is already active, nothing is changed.
     *
     * In CLI/test contexts without active session handling, starting is
     * skipped so that the class does not fail there with warnings.
     */
    public function startIfNeeded(): void
    {
        if (session_status() === PHP_SESSION_ACTIVE) {
            return;
        }

        if (session_status() === PHP_SESSION_DISABLED || PHP_SAPI === 'cli') {
            // Without session handling (e.g. CLI) no session is started.
            return;
        }

        // Only accept session ids generated by the server (protection against
        // injected ids, session fixation).
        ini_set('session.use_strict_mode', '1');
        ini_set('session.use_only_cookies', '1');

        // Sichere Cookie-Attribute setzen, bevor die Sitzung startet (R5.2).
        session_set_cookie_params([
            'lifetime' => 0,
            'path'     => '/',
            'httponly' => true,
            'samesite' => 'Strict',
            'secure'   => $this->isHttps(),
        ]);

        session_start();
    }

    public function set(string $key, int|string $value): void
    {
        $this->startIfNeeded();
        $_SESSION[$key] = $value;
    }

    public function retrieve(string $key): int|string|null
    {
        $this->startIfNeeded();

        $value = $_SESSION[$key] ?? null;

        if (is_int($value) || is_string($value)) {
            return $value;
        }

        return null;
    }

    public function remove(string $key): void
    {
        $this->startIfNeeded();
        unset($_SESSION[$key]);
    }

    public function regenerateId(): void
    {
        $this->startIfNeeded();

        if (session_status() === PHP_SESSION_ACTIVE) {
            // Alte Sitzungskennung verwerfen, Sitzungsdaten behalten (R5.2).
            session_regenerate_id(true);
        }
    }

    public function end(): void
    {
        $this->startIfNeeded();

        $_SESSION = [];

        if (session_status() === PHP_SESSION_ACTIVE) {
            session_destroy();
        }
    }

    /**
     * Detects whether the current request runs over HTTPS, to set the `Secure`
     * flag of the session cookie accordingly.
     */
    private function isHttps(): bool
    {
        return TransportSecurity::isHttps($_SERVER);
    }
}
